#!/usr/bin/env node
/* The build of the web documentation: Node only, no browser.
 *
 *   node docs/web/tools/build.mjs                 validate every page, write nav and search
 *   node docs/web/tools/build.mjs --check         validate only (writes nothing)
 *   node docs/web/tools/build.mjs --page basics/timeline   report one page (all are still read;
 *                                 repeat it or give a comma list; the others are one line)
 *   node docs/web/tools/build.mjs --strict        warnings count as errors
 *   node docs/web/tools/build.mjs --quiet         errors and the summary only
 *   node docs/web/tools/build.mjs --fix-sizes --page basics/timeline   set width and height of
 *                                 the page's images and clips from the media manifests first
 *
 * It reads tools/site.config.mjs and every .html file under docs/web/ (but tools/), and writes
 * assets/nav.js (the sections and pages, for the sidebar and previous/next) and
 * assets/search-index.js (titles, headings and text, for the search). Both are generated: never
 * edit or commit them (the lead regenerates them after merging).
 *
 * What it checks, per page (an error makes the exit code 1):
 *   - the head: charset, viewport, <title>, description, mfe:id equal to the page's path,
 *     mfe:level (and mfe:difficulty for a tutorial, mfe:status when "stub"), site.css and the three
 *     scripts nav.js, search-index.js and site.js; a level that differs from the config's;
 *   - main#content > article.doc, exactly one h1, an id on every h2 and h3, no id twice;
 *   - every relative href and src points to a file that exists, and a #anchor to an id of its page;
 *     nothing loaded from the network, no module scripts, no iframes;
 *   - images and videos: alt, width and height; a themed file has its .light. twin; the size
 *     matches media/<page-id>/manifest.json when there is one;
 *   - components: an example's slug has its examples/<slug>.data.js on the page (and the data has
 *     what the component needs), a player has assets/player.js, a tour has its .tour.js (and its
 *     images exist), a widget has widgets/<name>.js and valid data-options (and the example a
 *     widget of widgets/src/ names has its data); callouts and keys;
 *   - quoted code: the text of an element with data-excerpt="<file>" is in that file (readSource);
 *   - the site: every page of the config exists; a page missing from the config is reported
 *     (pages under authoring/ are built and checked, and stay out of the navigation).
 *
 * Imports only Node's modules, the shared library and jsdom from app/node_modules. */
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, posix } from 'node:path';
import { pathToFileURL } from 'node:url';
import vm from 'node:vm';
import { importFromApp, REPO, WEB_DIR } from './lib/paths.mjs';
import { DIFFICULTIES, LEVELS, SECTIONS, UNLISTED } from './site.config.mjs';

const TITLE_SUFFIX = ' · Manim Formula Editor';
const GENERATED =
  '/* Generated by tools/build.mjs from tools/site.config.mjs and the pages — do not edit. */';
const SKIP_DIRS = new Set(['tools', 'node_modules']);
/** The target for all of docs/web/ is about 35–45 MB (tools/sizes.mjs says where the bytes are). */
const BUDGET_BYTES = 45 * 1024 * 1024;
const MAX_INDEXED_CHARS = 60_000;

const isUnlisted = (id) => UNLISTED.some((prefix) => id.startsWith(prefix));
const squash = (text) =>
  String(text || '')
    .replace(/\s+/g, ' ')
    .trim();

/** Every .html file under docs/web/ (but tools/), as paths relative to it with "/". */
function findPages(dir = WEB_DIR, prefix = '') {
  const found = [];
  for (const name of readdirSync(dir).sort()) {
    if (name.startsWith('.')) continue;
    const full = join(dir, name);
    const rel = prefix ? `${prefix}/${name}` : name;
    const stats = statSync(full);
    if (stats.isDirectory()) {
      if (!prefix && SKIP_DIRS.has(name)) continue;
      found.push(...findPages(full, rel));
    } else if (name.endsWith('.html')) {
      found.push(rel);
    }
  }
  return found;
}

/** The size of a folder, in bytes. */
function folderSize(dir) {
  let total = 0;
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    const stats = statSync(full);
    total += stats.isDirectory() ? folderSize(full) : stats.size;
  }
  return total;
}

/** A path relative to docs/web/ ("examples/x.data.js") from a reference in a page. Returns null
 * for what is not a local file (a scheme, a protocol-relative address, an anchor alone). */
function resolveLocal(pageRel, reference) {
  if (!reference) return null;
  const value = reference.trim();
  if (!value || value.startsWith('#')) return null;
  if (/^[a-z][a-z0-9+.-]*:/i.test(value) || value.startsWith('//')) return null;
  const [pathPart] = value.split(/[?#]/);
  if (!pathPart) return null;
  let decoded = pathPart;
  try {
    decoded = decodeURIComponent(pathPart);
  } catch {
    // keep it as written
  }
  const joined = posix.normalize(posix.join(posix.dirname(pageRel), decoded));
  return joined;
}

/** The files this build writes: they count as present before the first run, and with --check. */
const OUTPUTS = new Set(['assets/nav.js', 'assets/search-index.js']);

const fileExists = (rel) =>
  OUTPUTS.has(rel) || (!rel.startsWith('..') && existsSync(join(WEB_DIR, ...rel.split('/'))));

/** Runs a data script (examples/x.data.js, media/…/x.tour.js) in a sandbox and returns its
 * `window`. Cached; null when it cannot run. */
const dataCache = new Map();
function runDataScript(rel) {
  if (dataCache.has(rel)) return dataCache.get(rel);
  let result = null;
  try {
    const code = readFileSync(join(WEB_DIR, ...rel.split('/')), 'utf8');
    const sandbox = { window: {}, console: { log() {}, warn() {}, error() {} } };
    sandbox.self = sandbox.window;
    vm.runInNewContext(code, sandbox, { filename: rel, timeout: 5_000 });
    result = sandbox.window;
  } catch (error) {
    result = { error: error.message };
  }
  dataCache.set(rel, result);
  return result;
}

/** The manifest.json of a folder of media/ (`media/<page-id>`), read whatever its exact shape: a
 * list of { file|name|path, width, height, … } or a map from file name to { width, height, … }
 * (under `files` or not). Null when the folder has none. */
const manifestCache = new Map();
function readManifest(folder) {
  if (manifestCache.has(folder)) return manifestCache.get(folder);
  const rel = `${folder}/manifest.json`;
  let result = null;
  if (fileExists(rel)) {
    try {
      const json = JSON.parse(readFileSync(join(WEB_DIR, ...rel.split('/')), 'utf8'));
      const entries = new Map();
      const add = (name, info) => {
        if (!name || !info || typeof info !== 'object') return;
        const width = Number(info.width ?? info.w ?? info.cssWidth);
        const height = Number(info.height ?? info.h ?? info.cssHeight);
        entries.set(posix.basename(String(name)), { width, height });
      };
      const list = Array.isArray(json) ? json : Array.isArray(json?.files) ? json.files : null;
      if (list) for (const item of list) add(item?.file ?? item?.name ?? item?.path, item);
      else {
        const map = json?.files && typeof json.files === 'object' ? json.files : json;
        for (const [name, info] of Object.entries(map || {})) add(name, info);
      }
      result = { rel, entries };
    } catch (error) {
      result = { rel, error: error.message };
    }
  }
  manifestCache.set(folder, result);
  return result;
}

/** The text of the article for the search: chunks split at each h2/h3 with an id. */
function extractChunks(article) {
  const chunks = [[null, '']];
  const SKIP = new Set(['SCRIPT', 'STYLE', 'TEMPLATE', 'NOSCRIPT', 'SVG', 'NAV']);
  const BLOCK = /^(P|LI|DT|DD|TD|TH|H[1-6]|PRE|FIGCAPTION|BLOCKQUOTE|DIV|SECTION|ASIDE|TR|BR)$/;
  const walk = (node) => {
    for (const child of node.childNodes) {
      if (child.nodeType === 3) {
        chunks[chunks.length - 1][1] += child.nodeValue;
        continue;
      }
      if (child.nodeType !== 1) continue;
      const tag = child.tagName.toUpperCase();
      if (SKIP.has(tag)) continue;
      if (child.getAttribute('aria-hidden') === 'true' || child.hasAttribute('data-search-skip'))
        continue;
      if (child.classList.contains('stub') || child.classList.contains('stub-todo') || tag === 'H1')
        continue;
      if ((tag === 'H2' || tag === 'H3') && child.id) {
        chunks.push([child.id, '']);
        continue;
      }
      walk(child);
      if (BLOCK.test(tag)) chunks[chunks.length - 1][1] += ' ';
    }
  };
  walk(article);
  let budget = MAX_INDEXED_CHARS;
  let truncated = false;
  const out = [];
  for (const [id, text] of chunks) {
    let clean = squash(text);
    if (clean.length > budget) {
      clean = clean.slice(0, Math.max(0, budget));
      truncated = true;
    }
    budget -= clean.length;
    if (clean || id) out.push([id, clean]);
  }
  return { chunks: out, truncated };
}

/** Quoted code: the text of an element marked `data-excerpt="<file>"` must be found in that file.
 * The file is a path from docs/web/ (`examples/hero.ce.py`), the bare name of a file of
 * examples/ (`hero.ce.py`), or a path from the repository's root when it starts with `/`
 * (`/docs/FORMAT.md`). Every run of whitespace counts as one space (indentation and line breaks
 * may differ), a `…` (or a line of `...`, `# ...`) stands for what the excerpt leaves out — the
 * pieces around it are found in that order —, and lines holding the text of `data-excerpt-ignore`
 * (`# yours`) are the author's own and are not looked for. */
const sourceCache = new Map();
function readSource(reference) {
  const value = reference.trim();
  const rel = value.startsWith('/')
    ? value.replace(/^\/+/, '')
    : value.includes('/')
      ? posix.normalize(value.replace(/^\.\//, ''))
      : `examples/${value}`;
  const base = value.startsWith('/') ? REPO : WEB_DIR;
  const shown = value.startsWith('/') ? `/${rel}` : rel;
  const key = `${base}\u0000${rel}`;
  if (!sourceCache.has(key)) {
    let text = null;
    try {
      text = readFileSync(join(base, ...rel.split('/')), 'utf8');
    } catch {
      // reported by the caller
    }
    sourceCache.set(key, text === null ? null : squash(text));
  }
  return { shown, text: sourceCache.get(key) };
}

const GAP_LINE = /^\s*(?:(?:#|\/\/)\s*)?(?:…|\.\.\.)\s*$/;

/** null when `excerpt` is in `source` (both squashed), else what of it was not found. */
function findExcerpt(excerpt, source, ignore) {
  const lines = excerpt
    .split('\n')
    .filter((line) => !(ignore && line.includes(ignore)))
    .map((line) => (GAP_LINE.test(line) ? '…' : line));
  const pieces = lines
    .join('\n')
    .split('…')
    .map((piece) => squash(piece))
    .filter(Boolean);
  if (!pieces.length) return { piece: '', found: '' };
  let from = 0;
  for (const piece of pieces) {
    const at = source.indexOf(piece, from);
    if (at >= 0) {
      from = at + piece.length;
      continue;
    }
    if (from > 0 && source.includes(piece)) return { piece, found: '', order: true };
    // The longest beginning of the piece that is there, to say where the excerpt differs.
    const words = piece.split(' ');
    let low = 0;
    let high = words.length;
    while (low < high) {
      const mid = Math.ceil((low + high) / 2);
      if (source.indexOf(words.slice(0, mid).join(' '), from) >= 0) low = mid;
      else high = mid - 1;
    }
    return { piece, found: words.slice(0, low).join(' ') };
  }
  return null;
}

/** Reads and checks one page; returns what the site needs of it and its problems. */
function readPage(rel, JSDOM) {
  const id = rel.replace(/\.html$/, '');
  const problems = [];
  /** The files of docs/web/ the page loads or offers (not the pages it links): for sizes.mjs. */
  const uses = new Set();
  const error = (message) => problems.push({ level: 'error', message });
  const warn = (message) => problems.push({ level: 'warning', message });
  const source = readFileSync(join(WEB_DIR, ...rel.split('/')), 'utf8');
  const dom = new JSDOM(source);
  const document = dom.window.document;
  const q = (selector, scope = document) => scope.querySelector(selector);
  const qa = (selector, scope = document) => Array.from(scope.querySelectorAll(selector));
  const meta = (name) => q(`meta[name="${name}"]`)?.getAttribute('content')?.trim() ?? null;

  // The head.
  if (!/^<!doctype html>/i.test(source.trimStart()))
    error('the file does not start with <!doctype html>');
  if (!q('meta[charset]') || q('meta[charset]').getAttribute('charset').toLowerCase() !== 'utf-8') {
    error('missing <meta charset="utf-8">');
  }
  const viewport = meta('viewport');
  if (!viewport || !viewport.includes('width=device-width')) {
    error('missing <meta name="viewport" content="width=device-width, initial-scale=1">');
  }
  const title = squash(q('title')?.textContent);
  if (!title) error('missing <title>');
  else if (id !== 'index' && !title.endsWith(TITLE_SUFFIX))
    warn(`<title> should end with “${TITLE_SUFFIX}”`);
  const description = meta('description');
  if (!description) error('missing <meta name="description">');
  else if (description.length > 200)
    warn(`the description is ${description.length} characters (keep it under 200)`);
  const metaId = meta('mfe:id');
  if (metaId === null) error(`missing <meta name="mfe:id" content="${id}">`);
  else if (metaId !== id) error(`mfe:id is “${metaId}”, but the page is ${id}`);
  const level = meta('mfe:level');
  if (level === null) {
    if (id !== 'index') error('missing <meta name="mfe:level">');
  } else if (!LEVELS.includes(level)) {
    error(`mfe:level “${level}” is none of ${LEVELS.join(', ')}`);
  }
  const difficulty = meta('mfe:difficulty');
  if (difficulty !== null) {
    if (level !== 'tutorial') error('mfe:difficulty is for tutorials only');
    else if (!DIFFICULTIES.includes(difficulty)) {
      error(`mfe:difficulty “${difficulty}” is none of ${DIFFICULTIES.join(', ')}`);
    }
  }
  const status = meta('mfe:status');
  if (status !== null && status !== 'stub')
    error(`mfe:status “${status}”: the only status is “stub”`);
  const short = meta('mfe:short');
  if (short !== null && !short) error('mfe:short is empty');
  else if (short && short.length > 34)
    warn(`mfe:short is ${short.length} characters (the sidebar has room for about 30)`);

  const depth = rel.split('/').length - 1;
  const up = '../'.repeat(depth);
  const scripts = qa('script[src]');
  const scriptRels = scripts.map((node) => resolveLocal(rel, node.getAttribute('src')));
  const hasScript = (target) => scriptRels.includes(target);
  if (
    !qa('link[rel="stylesheet"]').some(
      (node) => resolveLocal(rel, node.getAttribute('href')) === 'assets/site.css',
    )
  ) {
    error(`missing <link rel="stylesheet" href="${up}assets/site.css">`);
  }
  for (const name of ['nav.js', 'search-index.js', 'site.js']) {
    const index = scriptRels.indexOf(`assets/${name}`);
    if (index < 0) error(`missing <script src="${up}assets/${name}" defer>`);
    else if (!scripts[index].hasAttribute('defer')) warn(`assets/${name} should load with defer`);
  }
  scripts.forEach((node, i) => {
    if (node.getAttribute('type') === 'module')
      error(`${node.getAttribute('src')}: no module scripts (the site opens from disk)`);
    else if (!node.hasAttribute('defer') && !node.hasAttribute('async') && scriptRels[i]) {
      warn(`${node.getAttribute('src')} should load with defer`);
    }
  });
  const inlineScripts = qa('script:not([src])').map((node) => node.textContent);
  const inlineMentions = (key) =>
    inlineScripts.some((code) => code.includes(`'${key}'`) || code.includes(`"${key}"`));

  // The body.
  const main = q('main#content');
  const article = main ? q('article.doc', main) : null;
  if (!main) error('missing <main id="content">');
  if (!article) error('missing <article class="doc"> inside <main id="content">');
  const h1s = qa('h1');
  if (h1s.length !== 1) error(`${h1s.length} h1 elements (a page has exactly one)`);
  else if (article && !article.contains(h1s[0])) error('the h1 is not inside the article');
  const h1 = squash(h1s[0]?.textContent);
  const inComponent = (node) =>
    node.closest('.demo, .mfe-widget, .mfe-player, .mfe-tour, .example-card');
  for (const heading of qa('h2, h3', article || document)) {
    if (!heading.id && !inComponent(heading)) {
      error(
        `<${heading.tagName.toLowerCase()}> “${squash(heading.textContent)}” has no id (anchors and the contents need one)`,
      );
    }
  }
  const ids = new Map();
  for (const node of qa('[id]')) ids.set(node.id, (ids.get(node.id) || 0) + 1);
  for (const [value, count] of ids)
    if (count > 1) error(`the id “${value}” is used ${count} times`);

  // Links and files.
  const references = [];
  const addRef = (node, attribute) => {
    const value = node.getAttribute(attribute);
    if (value !== null) references.push({ node, attribute, value });
  };
  qa('a[href], link[href]').forEach((node) => addRef(node, 'href'));
  qa('script[src], img[src], source[src], video[src], audio[src], track[src], embed[src]').forEach(
    (node) => addRef(node, 'src'),
  );
  qa('video[poster]').forEach((node) => addRef(node, 'poster'));
  qa('img[srcset], source[srcset]').forEach((node) => {
    for (const candidate of node.getAttribute('srcset').split(',')) {
      const value = candidate.trim().split(/\s+/)[0];
      if (value) references.push({ node, attribute: 'srcset', value });
    }
  });
  const links = [];
  for (const { node, attribute, value } of references) {
    const tag = node.tagName.toLowerCase();
    const loads = !(
      tag === 'a' ||
      (tag === 'link' && !/stylesheet|icon|preload/.test(node.getAttribute('rel') || ''))
    );
    if (/^(https?:)?\/\//i.test(value.trim())) {
      if (loads) error(`<${tag} ${attribute}="${value}">: nothing is loaded from the network`);
      continue;
    }
    if (/^javascript:/i.test(value.trim())) {
      error(`<${tag} ${attribute}="${value}">: no javascript: links`);
      continue;
    }
    if (value.trim().startsWith('#')) {
      const anchor = decodeURIComponent(value.trim().slice(1));
      if (anchor && !ids.has(anchor)) error(`${value}: no element with that id on this page`);
      continue;
    }
    const target = resolveLocal(rel, value);
    if (target === null) continue;
    if (!fileExists(target)) {
      error(`${attribute}="${value}": ${target} does not exist`);
      continue;
    }
    if (!target.endsWith('.html')) uses.add(target);
    const hash = value.includes('#') ? value.slice(value.indexOf('#') + 1) : '';
    if (hash && target.endsWith('.html'))
      links.push({ target, anchor: decodeURIComponent(hash), value });
  }
  for (const node of qa('iframe, object'))
    error(`<${node.tagName.toLowerCase()}>: no frames or objects (the site opens from disk)`);
  for (const node of qa('a[target="_blank"]')) {
    if (!/noopener/.test(node.getAttribute('rel') || ''))
      warn(`a link with target="_blank" needs rel="noopener": ${node.getAttribute('href')}`);
  }

  // Images and videos. A capture is checked against the manifest of its own folder (a page may
  // show the capture of another page).
  const badManifests = new Set();
  const checkSize = (node, src) => {
    const width = node.getAttribute('width');
    const height = node.getAttribute('height');
    const target = resolveLocal(rel, src);
    if (!target || !target.startsWith('media/')) return;
    const manifest = readManifest(posix.dirname(target));
    if (manifest?.error && !badManifests.has(manifest.rel)) {
      badManifests.add(manifest.rel);
      error(`${manifest.rel} is not valid JSON: ${manifest.error}`);
    }
    if (!manifest?.entries) return;
    const entry = manifest.entries.get(posix.basename(target));
    if (!entry) {
      warn(`${src} is not listed in ${manifest.rel}`);
      return;
    }
    if (Number(width) !== entry.width || Number(height) !== entry.height) {
      error(
        `${src} is ${entry.width}×${entry.height} in the manifest, the page says ${width}×${height} (--fix-sizes sets it)`,
      );
    }
  };
  const checkThemed = (node, attribute) => {
    const value = node.getAttribute(attribute);
    if (!value) return;
    if (!/\.dark\.[^/.]+$/.test(value.split(/[?#]/)[0])) {
      error(`${attribute}="${value}" of a data-themed element must name the .dark. file`);
      return;
    }
    const light = resolveLocal(rel, value.replace(/\.dark\.(?=[^/.]+$)/, '.light.'));
    if (light && !fileExists(light)) error(`${value}: its light twin ${light} does not exist`);
    else if (light) uses.add(light);
  };
  for (const img of qa('img')) {
    const src = img.getAttribute('src') || '';
    if (!img.hasAttribute('alt')) error(`<img src="${src}"> has no alt`);
    if (!img.hasAttribute('width') || !img.hasAttribute('height'))
      error(`<img src="${src}"> needs width and height`);
    if (img.hasAttribute('data-themed')) checkThemed(img, 'src');
    if (src.startsWith(`${up}media/`) || resolveLocal(rel, src)?.startsWith('media/')) {
      if (img.getAttribute('loading') !== 'lazy')
        warn(`<img src="${src}"> should have loading="lazy"`);
    }
    checkSize(img, src);
  }
  for (const video of qa('video')) {
    const src = video.getAttribute('src') || '';
    if (video.hasAttribute('data-themed')) {
      checkThemed(video, 'src');
      checkThemed(video, 'poster');
    }
    if (video.classList.contains('mfe-clip')) {
      for (const attribute of ['muted', 'loop', 'playsinline']) {
        if (!video.hasAttribute(attribute))
          error(`the clip ${src} needs the ${attribute} attribute`);
      }
      if (video.getAttribute('preload') !== 'none')
        warn(`the clip ${src} should have preload="none"`);
      if (!video.hasAttribute('poster')) error(`the clip ${src} needs a poster`);
      if (!video.hasAttribute('width') || !video.hasAttribute('height'))
        error(`the clip ${src} needs width and height`);
      if (video.hasAttribute('autoplay'))
        error(`the clip ${src} must not autoplay (site.js plays it when it is seen)`);
      if (video.hasAttribute('controls'))
        warn(`the clip ${src} should not have controls (site.js gives it its own buttons)`);
      checkSize(video, src);
    }
    if (video.classList.contains('mfe-manim') && !video.hasAttribute('controls')) {
      warn(`the Manim video ${src} should have controls`);
    }
  }

  // Components and their data.
  const needExample = (node, slug, what) => {
    if (!slug) {
      error(`${what} without a slug`);
      return null;
    }
    if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(slug))
      warn(`“${slug}” is not a slug (lowercase words joined by hyphens)`);
    if (node.hasAttribute('data-inline')) {
      if (!inlineMentions(slug))
        error(`${what} “${slug}” is data-inline, but no inline script names it`);
      return null;
    }
    const script = `examples/${slug}.data.js`;
    if (!hasScript(script)) {
      error(`${what} “${slug}” needs <script src="${up}${script}" defer> on the page`);
      return null;
    }
    if (!fileExists(script)) return null;
    const window = runDataScript(script);
    if (window?.error) {
      error(`${script} does not run: ${window.error}`);
      return null;
    }
    const data = window?.MFE_EXAMPLES?.[slug];
    if (!data) error(`${script} does not set MFE_EXAMPLES['${slug}']`);
    return data || null;
  };
  for (const node of qa('[data-mfe-player]')) {
    // A showcase may name an example on purpose without its data, to show the player's notice.
    if (node.getAttribute('data-expect') !== 'missing') {
      needExample(node, node.getAttribute('data-mfe-player'), 'the player');
    }
    if (!hasScript('assets/player.js'))
      error(`a player needs <script src="${up}assets/player.js" defer> on the page`);
  }
  for (const node of qa('[data-mfe-python]')) {
    const data = needExample(node, node.getAttribute('data-mfe-python'), 'the Python of');
    if (data && !(typeof data.python?.ce === 'string' || typeof data.python?.gl === 'string')) {
      error(`the example “${node.getAttribute('data-mfe-python')}” has no python.ce nor python.gl`);
    }
  }
  for (const node of qa('[data-mfe-example]')) {
    const slug = node.getAttribute('data-mfe-example');
    const data = needExample(node, slug, 'the example card');
    if (data && !data.meta) error(`the example “${slug}” has no meta`);
    for (const [key, value] of Object.entries(data?.meta?.files || {})) {
      if (typeof value !== 'string' || /^[a-z][a-z0-9+.-]*:/i.test(value)) continue;
      const path = value.replace(/^\.\//, '').replace(/^\/+/, '');
      const target = path.includes('/') ? path : `examples/${path}`;
      if (!fileExists(target))
        error(`the example “${slug}”: its file ${key} (${target}) does not exist`);
      else uses.add(target);
    }
  }
  for (const node of qa('[data-mfe-tour]')) {
    const tourId = node.getAttribute('data-mfe-tour');
    if (!node.classList.contains('mfe-tour'))
      warn(`the tour “${tourId}” should have class="mfe-tour"`);
    if (!tourId || !tourId.includes('/')) {
      error(`data-mfe-tour “${tourId}” is not <page-id>/<tour>`);
      continue;
    }
    if (node.hasAttribute('data-inline')) {
      if (!inlineMentions(tourId))
        error(`the tour “${tourId}” is data-inline, but no inline script names it`);
      continue;
    }
    const script = `media/${tourId}.tour.js`;
    if (!hasScript(script)) {
      error(`the tour “${tourId}” needs <script src="${up}${script}" defer> on the page`);
      continue;
    }
    if (!fileExists(script)) continue;
    const window = runDataScript(script);
    const tour = window?.MFE_TOURS?.[tourId];
    if (window?.error) error(`${script} does not run: ${window.error}`);
    else if (!tour || !Array.isArray(tour.steps) || !tour.steps.length)
      error(`${script} does not set MFE_TOURS['${tourId}'] with steps`);
    else {
      const pageOfTour = tourId.slice(0, tourId.lastIndexOf('/'));
      const base =
        typeof tour.base === 'string' ? tour.base.replace(/^\/+/, '') : `media/${pageOfTour}/`;
      const ext = typeof tour.ext === 'string' ? tour.ext : 'webp';
      tour.steps.forEach((step, i) => {
        for (const which of ['dark', 'light']) {
          const image = `${base}${step?.image}.${which}.${ext}`;
          if (!fileExists(image))
            error(`the tour “${tourId}”, step ${i + 1}: ${image} does not exist`);
          else uses.add(image);
        }
        for (const box of step?.boxes || []) {
          const inside =
            box.x >= 0 &&
            box.y >= 0 &&
            box.x + box.w <= tour.width + 0.5 &&
            box.y + box.h <= tour.height + 0.5;
          if (!inside) warn(`the tour “${tourId}”, step ${i + 1}: a box leaves the image`);
        }
      });
    }
  }
  for (const node of qa('[data-mfe-widget]')) {
    const name = node.getAttribute('data-mfe-widget');
    if (node.hasAttribute('data-inline')) {
      if (!inlineMentions(name))
        error(`the widget “${name}” is data-inline, but no inline script names it`);
    } else if (!hasScript(`widgets/${name}.js`)) {
      error(`the widget “${name}” needs <script src="${up}widgets/${name}.js" defer> on the page`);
    }
    const options = node.getAttribute('data-options');
    let parsed = null;
    if (options) {
      try {
        parsed = JSON.parse(options);
      } catch (parseError) {
        error(`the widget “${name}”: data-options is not valid JSON (${parseError.message})`);
      }
    }
    // A widget of the documentation (widgets/src/) loads the player, the example its options name
    // and widgets.css when the page's head lacks them (widgets/README.md): the example's data
    // must exist. A showcase may name one on purpose without its data, to show the notice.
    const slug = parsed && typeof parsed === 'object' ? parsed.example : undefined;
    if (
      typeof slug === 'string' &&
      fileExists(`widgets/src/${name}.js`) &&
      node.getAttribute('data-expect') !== 'missing' &&
      !fileExists(`examples/${slug}.data.js`)
    ) {
      error(
        `the widget “${name}”: its example “${slug}” has no examples/${slug}.data.js (tools/examples.mjs build ${slug})`,
      );
    }
  }
  for (const node of qa('aside.callout')) {
    const kinds = ['tip', 'note', 'warning', 'platform'].filter((kind) =>
      node.classList.contains(kind),
    );
    if (kinds.length !== 1)
      error('a callout needs exactly one of the classes tip, note, warning or platform');
    if (
      kinds[0] === 'platform' &&
      !['mac', 'windows', 'linux'].includes(node.getAttribute('data-platform'))
    ) {
      error('a platform callout needs data-platform="mac", "windows" or "linux"');
    }
  }
  // A combination of keys: `data-keys`, and `data-keys-mac` for the one the app has on a Mac when
  // it is another. `Ctrl` is the Control key itself, on every system (⌃ on a Mac): it is what an
  // author means in a combination written for a Mac alone, and seldom elsewhere.
  for (const node of qa('kbd[data-keys], kbd[data-keys-mac]')) {
    if (!node.hasAttribute('data-keys')) {
      error(`kbd data-keys-mac="${node.getAttribute('data-keys-mac')}" has no data-keys`);
      continue;
    }
    const forMac = node.closest('.only-mac') !== null;
    for (const attribute of ['data-keys', 'data-keys-mac']) {
      if (!node.hasAttribute(attribute)) continue;
      const written = `kbd ${attribute}="${node.getAttribute(attribute)}"`;
      const keys = node
        .getAttribute(attribute)
        .split('+')
        .map((key) => key.trim());
      if (keys.some((key) => !key)) error(`${written} has an empty key (write Plus for +)`);
      for (const key of keys) {
        if (/^(Cmd|Command|Meta|Win|Option|Opt)$/i.test(key)) {
          error(`${written}: write Mod for Ctrl/⌘ and Alt for Alt/⌥`);
        } else if (key === 'Control') {
          error(`${written}: write Ctrl for the Control key itself`);
        } else if (key === 'Ctrl' && attribute === 'data-keys' && !forMac) {
          warn(`${written}: Ctrl is the Control key itself, ⌃ on a Mac; Mod is Ctrl or ⌘`);
        }
      }
    }
  }
  for (const node of qa('[data-excerpt]')) {
    const reference = node.getAttribute('data-excerpt') || '';
    const tag = `<${node.tagName.toLowerCase()} data-excerpt="${reference}">`;
    if (!reference.trim()) {
      error(`${tag}: data-excerpt names no file`);
      continue;
    }
    const { shown, text } = readSource(reference);
    if (text === null) {
      error(`${tag}: ${shown} does not exist`);
      continue;
    }
    const missing = findExcerpt(node.textContent, text, node.getAttribute('data-excerpt-ignore'));
    if (!missing) continue;
    const cut = (value) => (value.length > 70 ? `${value.slice(0, 70)}…` : value);
    if (!missing.piece) error(`${tag}: the excerpt is empty`);
    else if (missing.order) {
      error(`${tag}: “${cut(missing.piece)}” is in ${shown}, but not after what comes before it`);
    } else if (!missing.found) error(`${tag}: not in ${shown}: “${cut(missing.piece)}”`);
    else {
      error(
        `${tag}: not in ${shown}; it matches up to “${cut(missing.found.slice(-70))}”, then “${cut(missing.piece.slice(missing.found.length).trim())}” is not there`,
      );
    }
  }
  for (const node of qa('[data-options]:not([data-mfe-widget])')) {
    warn(`data-options on something that is not a widget (${node.tagName.toLowerCase()})`);
  }

  // What the site keeps of the page.
  const headings = qa('h2[id], h3[id]', article || document)
    .filter((node) => !inComponent(node))
    .map((node) => [node.id, squash(node.textContent)]);
  const { chunks, truncated } = article ? extractChunks(article) : { chunks: [], truncated: false };
  if (truncated)
    warn(`the page is long: the search indexes its first ${MAX_INDEXED_CHARS} characters`);
  dom.window.close();
  return {
    id,
    rel,
    title: h1 || title.replace(TITLE_SUFFIX, ''),
    short: short || null,
    description: description || '',
    level,
    difficulty,
    stub: status === 'stub',
    ids,
    links,
    uses,
    headings,
    chunks,
    problems,
  };
}

/** Sets the width and height of every <img> and <video> of a page whose file is in the
 * manifest.json of its media/ folder to the manifest's (what the build checks). Edits only those
 * two attributes, in the page's own text. Returns the changes: [{ src, from, to }]. */
export function fixSizes(rel) {
  const file = join(WEB_DIR, ...rel.split('/'));
  const source = readFileSync(file, 'utf8');
  const changes = [];
  const text = source.replace(/<(img|video)\b[^>]*>/gi, (tag) => {
    const src = /\ssrc="([^"]*)"/.exec(tag)?.[1];
    const target = src ? resolveLocal(rel, src) : null;
    if (!target || !target.startsWith('media/')) return tag;
    const manifest = readManifest(posix.dirname(target));
    const entry = manifest?.entries?.get(posix.basename(target));
    if (!entry || !(entry.width > 0) || !(entry.height > 0)) return tag;
    const now = (name) => new RegExp(`\\s${name}="([^"]*)"`).exec(tag)?.[1] ?? null;
    const before = `${now('width') ?? '?'}×${now('height') ?? '?'}`;
    let next = tag;
    for (const name of ['height', 'width']) {
      const value = String(entry[name]);
      const pattern = new RegExp(`(\\s)${name}="[^"]*"`);
      next = pattern.test(next)
        ? next.replace(pattern, `$1${name}="${value}"`)
        : next.replace(/(\ssrc="[^"]*")/, `$1 ${name}="${value}"`);
    }
    if (next !== tag) changes.push({ src, from: before, to: `${entry.width}×${entry.height}` });
    return next;
  });
  if (text !== source) writeFileSync(file, text);
  return changes;
}

/** Builds the site; returns { pages, problems: Map(id → problems), errors, warnings, files }. */
export async function build({ write = true } = {}) {
  const { JSDOM } = await importFromApp('jsdom/lib/api.js');
  const rels = findPages();
  const pages = new Map();
  for (const rel of rels) {
    const page = readPage(rel, JSDOM);
    pages.set(page.id, page);
  }
  const siteProblems = [];
  // Anchors into other pages. A page that is still a stub here (another author writes it, in
  // another checkout) gets its ids when it is written: a warning until then, not an error.
  for (const page of pages.values()) {
    for (const link of page.links) {
      const target = pages.get(link.target.replace(/\.html$/, ''));
      if (target && link.anchor && !target.ids.has(link.anchor)) {
        page.problems.push(
          target.stub
            ? {
                level: 'warning',
                message: `${link.value}: ${link.target} is a stub here, with no id “${link.anchor}” yet (an error once it is written)`,
              }
            : {
                level: 'error',
                message: `${link.value}: ${link.target} has no id “${link.anchor}”`,
              },
        );
      }
    }
  }
  // The config and the pages.
  const listed = new Set();
  const nav = { sections: [] };
  for (const section of SECTIONS) {
    const entry = { id: section.id, title: section.title, pages: [] };
    for (const planned of section.pages) {
      if (listed.has(planned.id))
        siteProblems.push({
          level: 'error',
          message: `${planned.id} is listed twice in the config`,
        });
      listed.add(planned.id);
      if (!planned.id.startsWith(`${section.id}/`)) {
        siteProblems.push({
          level: 'error',
          message: `${planned.id} is listed under the section “${section.id}”`,
        });
      }
      const page = pages.get(planned.id);
      if (!page) {
        siteProblems.push({
          level: 'error',
          message: `${planned.id}.html is in the config and does not exist`,
        });
        continue;
      }
      if (page.level && planned.level !== page.level) {
        page.problems.push({
          level: 'error',
          message: `mfe:level is “${page.level}”, the config plans “${planned.level}” (change both together)`,
        });
      }
      if ((planned.difficulty || null) !== (page.difficulty || null)) {
        page.problems.push({
          level: 'error',
          message: `mfe:difficulty is “${page.difficulty ?? ''}”, the config plans “${planned.difficulty ?? ''}”`,
        });
      }
      const item = {
        id: page.id,
        url: page.rel,
        title: page.title,
        level: page.level,
        description: page.description,
      };
      if (page.short) item.short = page.short;
      if (page.difficulty) item.difficulty = page.difficulty;
      if (page.stub) item.stub = true;
      entry.pages.push(item);
    }
    nav.sections.push(entry);
  }
  for (const page of pages.values()) {
    if (page.id === 'index' || isUnlisted(page.id) || listed.has(page.id)) continue;
    siteProblems.push({
      level: 'warning',
      message: `${page.rel} is not in tools/site.config.mjs (it stays out of the navigation)`,
    });
  }
  // The search index: every listed page.
  const sectionOf = new Map();
  for (const section of SECTIONS)
    for (const planned of section.pages) sectionOf.set(planned.id, section.title);
  const search = { pages: [] };
  for (const section of nav.sections) {
    for (const item of section.pages) {
      const page = pages.get(item.id);
      const entry = {
        id: page.id,
        url: page.rel,
        title: page.title,
        section: sectionOf.get(page.id) || '',
        level: page.level,
        description: page.description,
        headings: page.headings,
        chunks: page.chunks,
      };
      if (page.short) entry.short = page.short;
      if (page.difficulty) entry.difficulty = page.difficulty;
      search.pages.push(entry);
    }
  }
  const files = {};
  if (write) {
    const navText = `${GENERATED}\nwindow.MFE_NAV = ${JSON.stringify(nav, null, 1)};\n`;
    const searchText = `${GENERATED}\nwindow.MFE_SEARCH = ${JSON.stringify(search)};\n`;
    writeFileSync(join(WEB_DIR, 'assets', 'nav.js'), navText);
    writeFileSync(join(WEB_DIR, 'assets', 'search-index.js'), searchText);
    files.nav = Buffer.byteLength(navText);
    files.search = Buffer.byteLength(searchText);
  }
  const size = folderSize(WEB_DIR);
  if (size > BUDGET_BYTES) {
    siteProblems.push({
      level: 'warning',
      message: `docs/web/ is ${(size / 1048576).toFixed(1)} MB, over the target of about 35–45 MB (node docs/web/tools/sizes.mjs says where the weight is)`,
    });
  }
  let errors = siteProblems.filter((p) => p.level === 'error').length;
  let warnings = siteProblems.length - errors;
  for (const page of pages.values()) {
    for (const problem of page.problems) {
      if (problem.level === 'error') errors += 1;
      else warnings += 1;
    }
  }
  return { pages, siteProblems, errors, warnings, files, size, nav };
}

function parseArgs(argv) {
  const options = { write: true, only: null, strict: false, quiet: false, fixSizes: false };
  const addPages = (value) => {
    const ids = String(value || '')
      .split(',')
      .map((id) => id.trim().replace(/\.html$/, ''))
      .filter(Boolean);
    if (!ids.length) throw new Error('--page needs a page id');
    options.only = [...(options.only ?? []), ...ids];
  };
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg === '--check') options.write = false;
    else if (arg === '--fix-sizes') options.fixSizes = true;
    else if (arg === '--strict') options.strict = true;
    else if (arg === '--quiet') options.quiet = true;
    else if (arg === '--page') addPages(argv[++i]);
    else if (arg.startsWith('--page=')) addPages(arg.slice(7));
    else if (arg === '--help' || arg === '-h') options.help = true;
    else throw new Error(`unknown option ${arg}`);
  }
  return options;
}

async function main() {
  let options;
  try {
    options = parseArgs(process.argv.slice(2));
  } catch (error) {
    console.error(error.message);
    process.exit(2);
  }
  if (options.help) {
    console.log(
      'usage: node docs/web/tools/build.mjs [--check] [--page <id>] [--strict] [--quiet] [--fix-sizes]',
    );
    return;
  }
  const started = Date.now();
  if (options.fixSizes) {
    // Before the build reads the pages, so that its report is of the fixed pages.
    const rels = findPages().filter(
      (rel) => !options.only || options.only.includes(rel.replace(/\.html$/, '')),
    );
    let count = 0;
    for (const rel of rels) {
      const changes = fixSizes(rel);
      count += changes.length;
      if (changes.length) console.log(`  ${rel}: ${changes.length} size(s) set from the manifests`);
      for (const change of changes) console.log(`    ${change.src}: ${change.from} → ${change.to}`);
    }
    console.log(`--fix-sizes: ${count} size(s) set in ${rels.length} page(s)`);
  }
  const result = await build({ write: options.write });
  const lines = [];
  const show = (problem) => !options.quiet || problem.level === 'error';
  const ids = Array.from(result.pages.keys()).sort();
  const unknown = (options.only ?? []).filter((id) => !result.pages.has(id));
  if (unknown.length) {
    console.error(unknown.map((id) => `no page ${id} (docs/web/${id}.html)`).join('\n'));
    process.exit(2);
  }
  const reported = (id) => !options.only || options.only.includes(id);
  for (const id of ids) {
    if (!reported(id)) continue;
    const problems = result.pages.get(id).problems.filter(show);
    if (!problems.length) continue;
    lines.push(`  ${id}`);
    for (const problem of problems)
      lines.push(`    ${problem.level === 'error' ? 'error  ' : 'warning'} ${problem.message}`);
  }
  if (!options.only) {
    const site = result.siteProblems.filter(show);
    if (site.length) {
      lines.push('  (site)');
      for (const problem of site)
        lines.push(`    ${problem.level === 'error' ? 'error  ' : 'warning'} ${problem.message}`);
    }
  }
  let errors = result.errors;
  let warnings = result.warnings;
  let others = null;
  if (options.only) {
    const problems = options.only.flatMap((id) => result.pages.get(id).problems);
    errors = problems.filter((p) => p.level === 'error').length;
    warnings = problems.length - errors;
    // The rest of the site (another author's draft, the config) is one line, and fails nothing.
    const pagesWithErrors = ids.filter(
      (id) => !reported(id) && result.pages.get(id).problems.some((p) => p.level === 'error'),
    );
    if (result.siteProblems.some((p) => p.level === 'error')) pagesWithErrors.push('(site)');
    others = {
      errors: result.errors - errors,
      warnings: result.warnings - warnings,
      pages: pagesWithErrors,
    };
  }
  const stubs = Array.from(result.pages.values()).filter((page) => page.stub).length;
  if (lines.length) console.log(lines.join('\n'));
  if (others && (others.errors || others.warnings)) {
    const shown = others.pages.slice(0, 4).join(', ') + (others.pages.length > 4 ? ', …' : '');
    console.log(
      `other pages and the site: ${others.errors} error${others.errors === 1 ? '' : 's'}` +
        `${others.pages.length ? ` (${shown})` : ''}, ${others.warnings} warning${others.warnings === 1 ? '' : 's'} — not counted here`,
    );
  }
  const scope = options.only
    ? `page${options.only.length === 1 ? '' : 's'} ${options.only.join(', ')}`
    : `${result.pages.size} pages (${stubs} stubs)`;
  console.log(
    `docs/web build: ${scope}, ${errors} error${errors === 1 ? '' : 's'}, ${warnings} warning${warnings === 1 ? '' : 's'}` +
      ` · docs/web is ${(result.size / 1048576).toFixed(1)} MB · ${Date.now() - started} ms`,
  );
  if (options.write) {
    console.log(
      `wrote assets/nav.js (${(result.files.nav / 1024).toFixed(1)} KB) and assets/search-index.js (${(result.files.search / 1024).toFixed(1)} KB)`,
    );
  }
  if (errors > 0 || (options.strict && warnings > 0)) process.exitCode = 1;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch((error) => {
    console.error(error);
    process.exit(2);
  });
}
