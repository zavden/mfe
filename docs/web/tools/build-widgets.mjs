#!/usr/bin/env node
/* Builds the interactive widgets of the documentation: each `widgets/src/<name>.js` with the kit
 * they share (`widgets/src/kit.js`) into `widgets/<name>.js`, one classic script per widget, as
 * the pages load it (`<script src="../widgets/<name>.js" defer>`): the kit and the widget inside
 * one closure, so that two widgets on a page share nothing but `window.MFE_WIDGETS`.
 *
 *   node docs/web/tools/build-widgets.mjs           write widgets/<name>.js for every source
 *   node docs/web/tools/build-widgets.mjs --check   fail if a widget on disk is not what its
 *                                                   sources make now
 *
 * It compiles each script (a syntax error fails the build), checks that the widget registers
 * itself under its file's name, and that no widget is left whose source is gone. Node only: no
 * browser, no server, no lock. widgets/README.md is the guide. */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { Script } from 'node:vm';
import { REPO, WEB_DIR } from './lib/paths.mjs';

const SRC = join(WEB_DIR, 'widgets', 'src');
const OUT = join(WEB_DIR, 'widgets');
const KIT = 'kit.js';
const NAME = /^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$/;

const rel = (file) => relative(REPO, file).replaceAll('\\', '/');

/** The widgets' names: every source but the kit. */
function names() {
  return readdirSync(SRC)
    .filter((file) => file.endsWith('.js') && file !== KIT)
    .map((file) => file.slice(0, -3))
    .sort();
}

/** The script of widget `name`. */
function compose(name) {
  if (!NAME.test(name)) throw new Error(`widgets/src/${name}.js: a widget's name is a slug`);
  const kit = readFileSync(join(SRC, KIT), 'utf8').trimEnd();
  const own = readFileSync(join(SRC, `${name}.js`), 'utf8').trimEnd();
  if (!own.includes(`(window.MFE_WIDGETS ||= {})['${name}']`)) {
    throw new Error(
      `widgets/src/${name}.js does not register itself: (window.MFE_WIDGETS ||= {})['${name}'] = { mount(element, options, context) { … } }`,
    );
  }
  const script =
    `/* Generated by tools/build-widgets.mjs from widgets/src/${KIT} and widgets/src/${name}.js — ` +
    'do not edit. */\n' +
    '(() => {\n' +
    "'use strict';\n\n" +
    `${kit}\n\n` +
    `${own}\n` +
    '})();\n';
  try {
    new Script(script, { filename: `widgets/${name}.js` });
  } catch (error) {
    throw new Error(`widgets/${name}.js does not compile: ${error.message}`);
  }
  return script;
}

function main() {
  const check = process.argv.includes('--check');
  const unknown = process.argv.slice(2).filter((arg) => arg !== '--check');
  if (unknown.length > 0) throw new Error(`unknown arguments: ${unknown.join(' ')}`);
  if (!existsSync(join(SRC, KIT))) throw new Error(`no ${rel(join(SRC, KIT))}`);
  const widgets = names();
  const stale = [];
  for (const name of widgets) {
    const file = join(OUT, `${name}.js`);
    const script = compose(name);
    let current = null;
    try {
      current = readFileSync(file, 'utf8');
    } catch {
      // not built yet
    }
    if (current === script) continue;
    if (check) stale.push(rel(file));
    else {
      writeFileSync(file, script);
      console.log(`wrote ${rel(file)}: ${Buffer.byteLength(script).toLocaleString('en-US')} bytes`);
    }
  }
  // A built widget whose source is gone.
  const orphans = readdirSync(OUT)
    .filter((file) => file.endsWith('.js') && !widgets.includes(file.slice(0, -3)))
    .map((file) => rel(join(OUT, file)));
  if (orphans.length > 0) {
    throw new Error(`widgets without a source in widgets/src/: ${orphans.join(', ')}`);
  }
  if (stale.length > 0) {
    throw new Error(
      `not what the sources make now: ${stale.join(', ')} (run node docs/web/tools/build-widgets.mjs)`,
    );
  }
  console.log(
    `${widgets.length} widget${widgets.length === 1 ? '' : 's'} ${check ? 'up to date' : 'built'}: ${widgets.join(', ')}`,
  );
}

try {
  main();
} catch (error) {
  console.error(`build-widgets: ${error instanceof Error ? error.message : error}`);
  process.exit(1);
}
