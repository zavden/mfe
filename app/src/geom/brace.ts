/* Manim's braces, built in the browser as each library builds them (docs/ARCHITECTURE.md §5,
 * "Attached objects"), so that the brace of the preview is the brace Manim draws:
 *
 *   - ManimCE's `Brace` (mobject/svg/brace.py) is one SVG path: a template whose two straight
 *     runs grow with the target's width and `sharpness`, flipped, stretched to that width
 *     (`stretch_to_fit_width`, about the centre of its anchors) and placed under the target's
 *     left corner, `buff` away. The path is parsed as the library parses it (`parseSvgPath`:
 *     lines as cubics with their handles at thirds), so its 25 cubics are Manim's points.
 *   - ManimGL's `Brace` (mobject/svg/brace.py) is `Tex(r"\underbrace{\qquad}")`: six pieces — a
 *     hook, a rule, the two halves of the tip, a rule, a hook — whose rules stretch and whose
 *     hooks shift until the brace is as wide as the target (`set_initial_width`; a narrower one
 *     is squeezed whole), placed the same way. The pieces are a constant here, the quadratic
 *     points ManimGL holds at font size 48 (fixtures/manim/gen_brace.py): the font's cubics are
 *     turned into quadratics by the library with a choice that depends on float noise at one
 *     corner of each hook, which a conversion of the cubics cannot repeat.
 *
 * Both are built in the frame where the brace points down and rotated about the origin to the
 * direction asked, `degrees` counter-clockwise from DOWN (Manim's `angle = -atan2(x, y) + π` of
 * the direction vector). `braceShape` gives the pieces in that frame with the brace's upper-left
 * corner at the origin — the corner Manim shifts onto the target's lower-left corner — so a
 * placed brace is `shape`, moved by the target's corner and `buff` down, then rotated. The
 * callers centre it for a render (`engine/producers.ts`) and place it (`scene/attach.ts`, and
 * the Python's own `Brace(...)` does the same in Manim). */
import { pointPathBox, pointsToContours, toPointPath, type PointPath } from './morph';
import { parseSvgPath } from './path';
import type { Box, Contour, Mat2D, Vec2 } from './types';

/** The sides of a brace: a direction in degrees from DOWN, counter-clockwise. */
export type BraceTarget = 'ce' | 'gl';

