function apply(m: Mat2D, contours: readonly Contour[]): Contour[] {
  return contours.map((c) => {
    const out = new Array<number>(c.length);
    for (let i = 0; i < c.length; i += 2) {
      const x = c[i]!;
      const y = c[i + 1]!;
      out[i] = m[0] * x + m[2] * y + m[4];
      out[i + 1] = m[1] * x + m[3] * y + m[5];
    }
    return out;
  });
}

/** x ↦ at + (x − at)·factor, y unchanged. */
const stretchX = (factor: number, at: number): Mat2D => [factor, 0, 0, 1, at - at * factor, 0];
const shift = (dx: number, dy: number): Mat2D => [1, 0, 0, 1, dx, dy];

/** The box ManimCE reads corners from (the anchors) and the one it reads sizes from (every
 * point) of a path it holds as cubics. */
function ceBoxes(contours: readonly Contour[]): { anchors: Box; all: Box } {
  const path = toPointPath(contours, 'ce');
  return { anchors: pointPathBox(path, true)!, all: pointPathBox(path, false)! };
}

/** The box of every point of GL quadratics (what ManimGL reads everything from). */
function glBox(points: readonly number[]): Box {
  let minX = Infinity;
  let minY = Infinity;
  let maxX = -Infinity;
  let maxY = -Infinity;
  for (let i = 0; i < points.length; i += 2) {
    const x = points[i]!;
    const y = points[i + 1]!;
    if (x < minX) minX = x;
    if (x > maxX) maxX = x;
    if (y < minY) minY = y;
    if (y > maxY) maxY = y;
  }
  return { minX, minY, maxX, maxY };
}

/** ManimCE's brace of a target `width` wide, pointing down, its upper-left corner (of its
 * anchors, which is where Manim reads corners) at the origin: one closed contour of 25 cubics. */
export function ceBraceShape(width: number, sharpness: number): Contour[] {
  const run = Math.max(0, (width * sharpness - CE_BRACE_MIN_WIDTH) / 2);
  let contours = parseSvgPath(ceTemplate(run));
  // `self.flip(RIGHT)`: a half turn about the centre of the anchors' box, y → 2·cy − y.
  const flipped = ceBoxes(contours);
  const cy = (flipped.anchors.minY + flipped.anchors.maxY) / 2;
  contours = apply([1, 0, 0, -1, 0, 2 * cy], contours);
  // `stretch_to_fit_width(target_width)`: every point's width, about the anchors' centre.
  const boxes = ceBoxes(contours);
  const factor = width / (boxes.all.maxX - boxes.all.minX);
  contours = apply(stretchX(factor, (boxes.anchors.minX + boxes.anchors.maxX) / 2), contours);
  const { anchors } = ceBoxes(contours);
  return apply(shift(-anchors.minX, -anchors.maxY), contours);
}

/** ManimGL's brace of a target `width` wide, pointing down, its upper-left corner at the origin:
 * the six pieces (hook, rule, tip, tip, rule, hook) as cubic contours, raised from the quadratics
 * the library holds — `toPointPath(…, 'gl')` gives those quadratics back exactly. */
export function glBraceShape(width: number): Contour[] {
  const pieces = GL_BRACE_PIECES.map((p) => Float64Array.from(p));
  const whole = glBox(pieces.flatMap((p) => Array.from(p)));
  const diff = width - (whole.maxX - whole.minX);
  const stretchPoints = (points: Float64Array, m: Mat2D) => {
    for (let i = 0; i < points.length; i += 2) {
      points[i] = m[0] * points[i]! + m[4];
    }
  };
  if (diff > 0) {
    // `set_initial_width`: each rule grows by half the difference about its outer edge, and
    // the hook beyond it moves out by as much; the tip stays.
    for (const [hook, rule, outward] of [
      [0, 1, 1],
      [5, 4, -1],
    ] as const) {
      const box = glBox(Array.from(pieces[rule]!));
      const own = box.maxX - box.minX;
      const edge = outward > 0 ? box.maxX : box.minX;
      stretchPoints(pieces[rule]!, stretchX((diff / 2 + own) / own, edge));
      stretchPoints(pieces[hook]!, shift(-(diff / 2) * outward, 0));
    }
  } else {
    // `set_width(width, stretch=True)`: the whole brace squeezed about its centre.
    const factor = width / (whole.maxX - whole.minX);
    const m = stretchX(factor, (whole.minX + whole.maxX) / 2);
    for (const p of pieces) stretchPoints(p, m);
  }
  const placed = glBox(pieces.flatMap((p) => Array.from(p)));
  for (const p of pieces) {
    for (let i = 0; i < p.length; i += 2) {
      p[i] = p[i]! - placed.minX;
      p[i + 1] = p[i + 1]! - placed.maxY;
    }
  }
  return pieces.flatMap((p) => pointsToContours({ degree: 2 }, p));
}

/** The brace of `target`'s library for a target `width` wide, pointing down, with its upper-left
 * corner at the origin (see the header): one contour in ManimCE, six in ManimGL, which ignores
 * `sharpness`. */
export function braceShape(target: BraceTarget, width: number, sharpness: number): Contour[] {
  return target === 'ce' ? ceBraceShape(width, sharpness) : glBraceShape(width);
}

/** Where the point Manim's `get_tip()` returns sits among the point lists of a brace that points
 * down (its pieces in order, as the library holds them): the point the library fixed when it built
 * the brace — in ManimCE the one nearest to the bottom edge centre of the anchors' box, in ManimGL
 * the lowest one — the first of each, as `np.argmin` finds it. The list it is in, and the offset of
 * its x there; null for a brace without points. A stretch, a move or a turn since would not change
 * the index Manim keeps: find it where the brace points down, read it where the brace is. */
export function braceTipIndex(
  target: BraceTarget,
  paths: readonly PointPath[],
): { path: number; offset: number } | null {
  let best: { path: number; offset: number } | null = null;
  if (target === 'ce') {
    let minX = Infinity;
    let maxX = -Infinity;
    let minY = Infinity;
    for (const path of paths) {
      const box = pointPathBox(path, true);
      if (!box) continue;
      minX = Math.min(minX, box.minX);
      maxX = Math.max(maxX, box.maxX);
      minY = Math.min(minY, box.minY);
    }
    const bx = (minX + maxX) / 2;
    let bestD = Infinity;
    for (let p = 0; p < paths.length; p++) {
      const points = paths[p]!.points;
      for (let i = 0; i < points.length; i += 2) {
        const d = Math.hypot(points[i]! - bx, points[i + 1]! - minY);
        if (d < bestD) {
          bestD = d;
          best = { path: p, offset: i };
        }
      }
    }
  } else {
    let bestY = Infinity;
    for (let p = 0; p < paths.length; p++) {
      const points = paths[p]!.points;
      for (let i = 0; i < points.length; i += 2) {
        if (points[i + 1]! < bestY) {
          bestY = points[i + 1]!;
          best = { path: p, offset: i };
        }
      }
    }
  }
  return best;
}

/** Manim's `get_tip()` of a brace built by `braceShape` and moved since by `m` (`braceTipIndex`,
 * read where `m` puts it). */
export function braceTip(target: BraceTarget, shape: readonly Contour[], m: Mat2D): Vec2 {
  const built = toPointPath(shape, target);
  const at = braceTipIndex(target, [built])!.offset;
  const x = built.points[at]!;
  const y = built.points[at + 1]!;
  return [m[0] * x + m[2] * y + m[4], m[1] * x + m[3] * y + m[5]];
}
